//! brickie-rustscan: a dependency-free Rust tokenizer and scanner for `use` declarations.
//!
//! SCIP from rust-analyzer has no Import role, so we compute the source range of
//! every `use` item from the same source snapshot and classify occurrences by
//! containment.
//!
//! Position encoding: matches the SCIP output measured in the design doc
//! (`position_encoding = UTF8CodeUnitOffsetFromLineStart`): `line` is 0-based and
//! `col` is a 0-based **UTF-8 byte** offset from the line start. If a SCIP file
//! declares UTF-16, convert columns before calling [`UseItem::contains`].
//!
//! Known limits: `use` generated by macros is invisible; `use` inside
//! `macro_rules!` bodies is skipped (so it is not marked import); `use` inside
//! other macro invocation bodies (`foo! { use a::b; }`) is treated as an item;
//! `extern crate` is not a use item; a `use` after an expression-ending `}`
//! or `]` in a non-item context is accepted (harmless, `use` is a keyword).

#[cfg(test)]
mod tests;
pub mod tokenizer;

use tokenizer::{Kind, is_ident, is_punct, skip_group, tokenize};

/// A 0-based (line, UTF-8 byte column) position.
pub type Pos = (u32, u32);

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct UseItem {
    /// Byte offsets into the source: `start` at `pub`/`use`, `end` just past `;`.
    pub start: usize,
    pub end: usize,
    pub start_pos: Pos,
    pub end_pos: Pos,
    pub is_pub: bool,
    /// Visibility with whitespace removed: "", "pub", "pub(crate)", "pub(in crate::x)"...
    pub vis: String,
}

impl UseItem {
    /// True if `(line, col)` lies in `[start_pos, end_pos)`.
    pub fn contains(&self, line: u32, col: u32) -> bool {
        (line, col) >= self.start_pos && (line, col) < self.end_pos
    }
}

/// Collapse whitespace: `pub ( in a::b )` -> `pub(in a::b)`.
fn normalize_vis(raw: &str) -> String {
    let joined = raw.split_whitespace().collect::<Vec<_>>().join(" ");
    joined
        .replace("( ", "(")
        .replace(" )", ")")
        .replace(" (", "(")
}

/// All `use` items of `src`, sorted by position and disjoint.
pub fn use_items(src: &str) -> Vec<UseItem> {
    let toks = tokenize(src);
    let mut line_starts = vec![0usize];
    line_starts.extend(src.match_indices('\n').map(|(i, _)| i + 1));
    let pos = |off: usize| -> Pos {
        let line = line_starts.partition_point(|&s| s <= off) - 1;
        (line as u32, (off - line_starts[line]) as u32)
    };

    let mut out = Vec::new();
    let mut item_start = true;
    let mut i = 0;
    while i < toks.len() {
        let t = toks[i];
        if t.kind == Kind::Ident
            && &src[t.start..t.end] == "macro_rules"
            && is_punct(toks.get(i + 1), b'!')
        {
            // skip `macro_rules! name { ... }`
            let mut j = i + 2;
            if toks.get(j).is_some_and(|t| t.kind == Kind::Ident) {
                j += 1;
            }
            i = if is_punct(toks.get(j), b'{')
                || is_punct(toks.get(j), b'(')
                || is_punct(toks.get(j), b'[')
            {
                skip_group(&toks, j)
            } else {
                j
            };
            item_start = true;
            continue;
        }
        if is_punct(Some(&t), b'#') {
            let mut j = i + 1;
            if is_punct(toks.get(j), b'!') {
                j += 1;
            }
            if is_punct(toks.get(j), b'[') {
                i = skip_group(&toks, j);
                item_start = true;
                continue;
            }
        }
        if item_start && t.kind == Kind::Ident {
            let word = &src[t.start..t.end];
            let mut j = i;
            let mut vis_end = None;
            if word == "pub" {
                j += 1;
                if is_punct(toks.get(j), b'(') {
                    j = skip_group(&toks, j);
                }
                vis_end = Some(toks[j - 1].end);
            }
            if is_ident(src, toks.get(j), "use") {
                let mut depth = 0i32;
                let mut k = j + 1;
                let mut end = src.len();
                while k < toks.len() {
                    match toks[k].kind {
                        Kind::Punct(b'{') => depth += 1,
                        Kind::Punct(b'}') => depth -= 1,
                        Kind::Punct(b';') if depth <= 0 => {
                            end = toks[k].end;
                            break;
                        }
                        _ => {}
                    }
                    k += 1;
                }
                let vis = vis_end
                    .map(|e| normalize_vis(&src[t.start..e]))
                    .unwrap_or_default();
                out.push(UseItem {
                    start: t.start,
                    end,
                    start_pos: pos(t.start),
                    end_pos: pos(end),
                    is_pub: !vis.is_empty(),
                    vis,
                });
                i = (k + 1).min(toks.len());
                item_start = true;
                continue;
            }
        }
        item_start = matches!(t.kind, Kind::Punct(b';' | b'{' | b'}'));
        i += 1;
    }
    out
}
